// Post-build: print content gaps, write docs/CONTENT-GAPS.md, enforce production gate,
// and strip internal QA artefacts from production output.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const mode = process.env.CONTENT_MODE === "production" ? "production" : "preview";
const gapsFile = new URL("../dist/qa/content-gaps.json", import.meta.url);
if (!existsSync(gapsFile)) {
  console.error("postbuild: dist/qa/content-gaps.json missing — build incomplete");
  process.exit(1);
}
const { gaps } = JSON.parse(readFileSync(gapsFile, "utf8"));
const blocking = gaps.filter((g) => g.blocking);

const md = [
  "# Content gaps (generated)",
  "",
  `Generated by \`scripts/postbuild.mjs\` · mode: **${mode}** · ${new Date().toISOString()}`,
  "",
  "| # | Area | Blocking prod | Line |",
  "|---|---|---|---|",
  ...gaps.map((g, i) => `| ${i + 1} | ${g.area} | ${g.blocking ? "**YES**" : "no"} | ${g.line} |`),
  "",
].join("\n");
mkdirSync(new URL("../docs/", import.meta.url), { recursive: true });
writeFileSync(new URL("../docs/CONTENT-GAPS.md", import.meta.url), md);

console.log(`\nContent gaps: ${gaps.length} (${blocking.length} blocking production)`);
for (const g of gaps) console.log(`  ${g.blocking ? "✖" : "·"} ${g.line}`);

if (mode === "production") {
  rmSync(new URL("../dist/qa", import.meta.url), { recursive: true, force: true });
  if (blocking.length) {
    console.error(`\nPRODUCTION GATE FAILED: ${blocking.length} blocking item(s). dist/ must not be deployed.`);
    process.exit(1);
  }
  console.log("\nProduction gate passed.");
} else {
  console.log("\nPreview build (noindex). Run `npm run build:production` once blocking data exists.");
}
